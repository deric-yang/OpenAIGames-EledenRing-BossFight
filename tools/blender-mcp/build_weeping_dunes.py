def build_brazier(name, x, y, mats, index):
    base = terrain_height(x, y)
    bpy.ops.mesh.primitive_cylinder_add(vertices=10, radius=0.72, depth=0.42, location=(x, y, base + 1.45))
    bowl = bpy.context.object
    bowl.name = project_name(f"{name}_Bowl_{index:02d}")
    finish_object(bowl, collection("Foreground"), mats["iron"])
    for leg_index, angle in enumerate((0.0, 2.1, 4.2)):
        px = x + math.cos(angle) * 0.45
        py = y + math.sin(angle) * 0.45
        cone_between(f"{name}_Leg_{index:02d}_{leg_index}", (px, py, base + 0.1), (px, py, base + 1.3), 0.11, 0.08, mats["iron"], collection("Foreground"), vertices=6)
    ico(f"{name}_Flame_{index:02d}", (x, y, base + 2.05), (0.4, 0.4, 0.75), mats["flame"], collection("Atmosphere"), subdivisions=1)


