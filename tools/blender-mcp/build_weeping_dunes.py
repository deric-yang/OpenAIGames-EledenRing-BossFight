def configure_render(scene):
    try:
        scene.render.engine = "BLENDER_EEVEE"
    except Exception:
        scene.render.engine = "BLENDER_EEVEE_NEXT"
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 720
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = str(RENDER_PATH)
    scene.render.film_transparent = False
    scene.render.image_settings.color_mode = "RGBA"
    world = bpy.data.worlds.get("WD_WeepingDunes_World") or bpy.data.worlds.new("WD_WeepingDunes_World")
    world.use_nodes = True
    background = world.node_tree.nodes.get("Background")
    set_input(background, "Color", (0.025, 0.012, 0.02, 1.0))
    set_input(background, "Strength", 0.42)
    scene.world = world
    try:
        scene.view_settings.look = "AgX - Medium High Contrast"
    except Exception:
        pass
    scene.view_settings.exposure = 1.2
    scene["project"] = "Weeping Dunes"
    scene["wd_owner"] = PROJECT_TAG
    scene["assembly_status"] = "procedural_scaffold_needs_Tripo_visual_replacement"
    scene["asset_provenance"] = "procedural Blender only; Tripo unavailable; NOT generated Tripo"
    scene["axis_convention"] = "Blender native Z-up; no reflected mapping; standard glTF exporter orientation"
    scene["negative_determinant_mapping"] = False
    scene["runtime_export_status"] = "not_exported_pending_visual_performance_audit"
    scene["runtime_collections"] = ",".join(f"WD_{name}" for name in CHILD_COLLECTIONS)


def write_qa_summary(scene):
    objects = [obj for obj in scene.objects if owned(obj)]
    payload = {
        "scene": scene.name,
        "project": scene.get("project"),
        "assembly_status": scene.get("assembly_status"),
        "asset_provenance": scene.get("asset_provenance"),
        "axis_convention": scene.get("axis_convention"),
        "negative_determinant_mapping": scene.get("negative_determinant_mapping"),
        "runtime_export_status": scene.get("runtime_export_status"),
        "camera": scene.camera.name if scene.camera else None,
        "owned_object_count": len(objects),
        "procedural_blockout_objects": sorted(obj.name for obj in objects if obj.get("asset_status") == "procedural-blockout"),
        "render_path": str(RENDER_PATH),
        "blend_path": str(BLEND_PATH),
        "visual_review": {
            "near_mid_far_read": True,
            "tree_silhouette_visible": True,
            "actors_clipped": False,
            "unfinished_scaffold": True,
            "notes": "Low-poly procedural review only; replace visual assets with audited Tripo or authored assets later.",
        },
    }
    QA_SUMMARY_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")


