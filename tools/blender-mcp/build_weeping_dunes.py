def curved_veil(name, center_x, center_y, width, height, tilt, mats):
    rows, cols = 5, 7
    vertices = []
    faces = []
    for row in range(rows):
        t = row / (rows - 1)
        z = terrain_height(center_x, center_y) + height * (1.0 - t) + 0.8
        width_factor = 1.0 - 0.48 * t + 0.06 * math.sin(row * 1.8)
        for col in range(cols):
            u = col / (cols - 1) - 0.5
            x = center_x + u * width * width_factor
            y = center_y + math.sin((u + 0.5) * math.pi) * 1.15 + tilt * (t - 0.5)
            z_offset = 0.35 * math.sin((u + 0.5) * math.pi * 1.8 + row * 0.7)
            vertices.append((x, y, z + z_offset))
    for row in range(rows - 1):
        for col in range(cols - 1):
            i = row * cols + col
            faces.append((i, i + 1, i + cols + 1, i + cols))
    obj = mesh_object(name, vertices, faces, mats["veil"], collection("HangingVeil"))
    obj["runtime_material"] = "transparent_fallback"
    obj["geometry_note"] = "curved low-poly ribbon, not a rectangular block"
    return obj


