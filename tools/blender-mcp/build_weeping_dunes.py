def owned(item) -> bool:
    return item.get("wd_owner") == PROJECT_TAG


def tag(item, asset_status="procedural"):
    item["wd_owner"] = PROJECT_TAG
    item["asset_status"] = asset_status
    item["source"] = "procedural Blender scaffold; NOT generated Tripo"
    return item


def find_owned_scene():
    for scene in bpy.data.scenes:
        if owned(scene):
            return scene
    return None


def find_owned_master():
    for coll in bpy.data.collections:
        if owned(coll) and coll.get("wd_role") == "master":
            return coll
    return None


def unique_name(base, existing):
    if existing is None or existing.name == base:
        return base
    index = 2
    while f"{base}_Project{index:02d}" in bpy.data.scenes or f"{base}_Project{index:02d}" in bpy.data.collections:
        index += 1
    return f"{base}_Project{index:02d}"


def get_or_create_scene():
    scene = find_owned_scene()
    if scene is None:
        existing = bpy.data.scenes.get(SCENE_NAME)
        name = SCENE_NAME if existing is None else unique_name(SCENE_NAME, existing)
        scene = bpy.data.scenes.new(name)
        tag(scene, "review-scene")
        scene["wd_role"] = "review-scene"
    return scene


def get_or_create_master(scene):
    master = find_owned_master()
    if master is None:
        existing = bpy.data.collections.get(MASTER_COLLECTION_NAME)
        name = MASTER_COLLECTION_NAME if existing is None else f"{MASTER_COLLECTION_NAME}_Project"
        master = bpy.data.collections.new(name)
        tag(master, "review-assembly")
        master["wd_role"] = "master"
    if master.name not in {child.name for child in scene.collection.children}:
        scene.collection.children.link(master)
    return master


def clear_owned_master(master):
    # Only remove objects and child collections carrying our explicit ownership
    # tag. Untagged collections/objects, including user-owned scene content,
    # remain untouched. Rebuilding the owned boundary from scratch avoids
    # Blender's .001/.002 name accumulation without touching other projects.
    for obj in list(bpy.data.objects):
        if owned(obj):
            bpy.data.objects.remove(obj, do_unlink=True)
    for child in list(master.children):
        if owned(child):
            bpy.data.collections.remove(child)
    for obj in list(master.objects):
        if owned(obj):
            bpy.data.objects.remove(obj, do_unlink=True)


def make_collections(master):
    result = {}
    for short_name in CHILD_COLLECTIONS:
        name = f"WD_{short_name}"
        coll = bpy.data.collections.get(name)
        if coll is None or not owned(coll):
            coll = bpy.data.collections.new(name)
            tag(coll, "collection")
        if coll.name not in {child.name for child in master.children}:
            master.children.link(coll)
        result[short_name] = coll
    return result


def collection(name):
    return COLLECTIONS[name]


def move_to(obj, target_collection):
    for owner in list(obj.users_collection):
        owner.objects.unlink(obj)
    target_collection.objects.link(obj)
    return obj


def set_input(shader, name, value):
    socket = shader.inputs.get(name)
    if socket is not None:
        socket.default_value = value


def material(name, color, roughness=0.8, metallic=0.0, emission=None, emission_strength=0.0, alpha=1.0):
    mat_name = f"WD_{name}"
    mat = bpy.data.materials.get(mat_name) or bpy.data.materials.new(mat_name)
    tag(mat, "procedural-material")
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    shader = nodes.get("Principled BSDF")
    set_input(shader, "Base Color", (*color, 1.0))
    set_input(shader, "Roughness", roughness)
    set_input(shader, "Metallic", metallic)
    set_input(shader, "Alpha", alpha)
    if emission:
        set_input(shader, "Emission Color", (*emission, 1.0))
        set_input(shader, "Emission", (*emission, 1.0))
        set_input(shader, "Emission Strength", emission_strength)
    if alpha < 1.0:
        try:
            mat.surface_render_method = "DITHERED"
        except Exception:
            try:
                mat.surface_render_method = "BLENDED"
            except Exception:
                pass
        if hasattr(mat, "use_screen_refraction"):
            mat.use_screen_refraction = True
    return mat


def project_name(name):
    return name if name.startswith("WD_") else f"WD_{name}"


def assign(obj, mat):
    if obj.data and hasattr(obj.data, "materials"):
        obj.data.materials.clear()
        obj.data.materials.append(mat)
    return obj


def finish_object(obj, target_collection, mat=None, asset_status="procedural"):
    obj.name = project_name(obj.name)
    tag(obj, asset_status)
    if mat is not None:
        assign(obj, mat)
    move_to(obj, target_collection)
    return obj


def cube(name, location, dimensions, mat, target_collection, bevel=0.0, rotation=None, asset_status="procedural"):
    bpy.ops.mesh.primitive_cube_add(location=location, rotation=rotation or (0.0, 0.0, 0.0))
    obj = bpy.context.object
    obj.name = project_name(name)
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    finish_object(obj, target_collection, mat, asset_status)
    if bevel:
        modifier = obj.modifiers.new("SoftWeathering", "BEVEL")
        modifier.width = bevel
        modifier.segments = 2
    return obj


def ico(name, location, scale, mat, target_collection, subdivisions=1, asset_status="procedural"):
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=subdivisions, radius=1.0, location=location)
    obj = bpy.context.object
    obj.name = project_name(name)
    obj.scale = scale
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    finish_object(obj, target_collection, mat, asset_status)
    return obj


def cone_between(name, start, end, radius_start, radius_end, mat, target_collection, vertices=8, asset_status="procedural"):
    start_v = Vector(start)
    end_v = Vector(end)
    delta = end_v - start_v
    length = delta.length
    if length <= 1e-4:
        return None
    bpy.ops.mesh.primitive_cone_add(
        vertices=vertices,
        radius1=radius_start,
        radius2=radius_end,
        depth=length,
        location=(start_v + end_v) * 0.5,
    )
    obj = bpy.context.object
    obj.name = project_name(name)
    obj.rotation_euler = delta.to_track_quat("Z", "Y").to_euler()
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    finish_object(obj, target_collection, mat, asset_status)
    bevel = obj.modifiers.new("EdgeWear", "BEVEL")
    bevel.width = min(max(radius_start, radius_end) * 0.16, 0.12)
    bevel.segments = 1
    return obj


def curve_line(name, points, mat, target_collection, bevel_depth=0.05, asset_status="procedural"):
    curve_data = bpy.data.curves.new(name, type="CURVE")
    curve_data.dimensions = "3D"
    curve_data.resolution_u = 1
    curve_data.bevel_depth = bevel_depth
    curve_data.bevel_resolution = 0
    spline = curve_data.splines.new("POLY")
    spline.points.add(len(points) - 1)
    for point, co in zip(spline.points, points):
        point.co = (*co, 1.0)
    obj = bpy.data.objects.new(project_name(name), curve_data)
    tag(obj, asset_status)
    assign(obj, mat)
    target_collection.objects.link(obj)
    return obj


def mesh_object(name, vertices, faces, mat, target_collection, asset_status="procedural"):
    mesh = bpy.data.meshes.new(project_name(name))
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(project_name(name), mesh)
    tag(mesh, asset_status)
    finish_object(obj, target_collection, mat, asset_status)
    return obj


def look_at(obj, target):
    direction = Vector(target) - obj.location
    obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()


def terrain_height(x, y):
    return (
        -0.25
        + 0.28 * math.sin(x * 0.21 + 0.7)
        + 0.22 * math.cos(y * 0.24 - 0.2)
        + 0.16 * math.sin((x + y) * 0.14)
        + 0.12 * math.cos((x - y) * 0.31)
    )


def build_ground(mats):
    vertices = []
    faces = []
    nx, ny = 33, 31
    min_x, max_x = -38.0, 38.0
    min_y, max_y = -38.0, 34.0
    for row in range(ny):
        y = min_y + (max_y - min_y) * row / (ny - 1)
        for col in range(nx):
            x = min_x + (max_x - min_x) * col / (nx - 1)
            vertices.append((x, y, terrain_height(x, y)))
    for row in range(ny - 1):
        for col in range(nx - 1):
            i = row * nx + col
            faces.append((i, i + 1, i + nx + 1, i + nx))
    mesh_object("Dune_Terrain_Undulation", vertices, faces, mats["sand"], collection("Ground"))
    cube("Dune_Terrain_Substrate", (0.0, -2.0, -1.3), (76.0, 72.0, 1.8), mats["sand_dark"], collection("Ground"), 0.5)
    for index, (x, y, sx, sy, sz) in enumerate(
        [(-27.0, -18.0, 10.0, 5.5, 1.3), (25.0, -22.0, 12.0, 6.0, 1.6), (-29.0, 13.0, 8.0, 4.5, 0.9), (29.0, 9.0, 9.0, 5.0, 1.1)]
    ):
        ico(
            f"Dune_Mound_{index:02d}",
            (x, y, terrain_height(x, y) + sz * 0.25),
            (sx, sy, sz),
            mats["sand_dark"],
            collection("Midground"),
            subdivisions=2,
        )


